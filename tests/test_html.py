"""Black-box contract tests for the HTML sanitizer.

These 15 tests are the fixed specification.  Do not edit this file while
fixing ``sanitize/html.py``.
"""

from copy import deepcopy

from sanitize.html import (
    allowed_tag,
    escape_text,
    safe_url,
    sanitize,
    sanitize_attrs,
    sanitize_batch,
    tokenize,
    validate_policy,
)

POLICY = {
    "allowed_tags": ["a", "b", "br", "i", "p"],
    "allowed_attrs": {
        "a": ["href", "title"],
        "*": ["class"],
    },
    "url_schemes": ["http", "https", "mailto"],
}


def _relative_text_drift(before: str, after: str) -> float:
    """Fraction of positions that differ; used for the 1e-9 text check."""
    if len(before) != len(after):
        return 1.0
    if not before:
        return 0.0
    return sum(left != right for left, right in zip(before, after)) / len(before)


def test_allowed_tag_rejects_prefix_lookalike():
    # Defect 1: startswith() whitelisting lets scriptx / bscript through.
    assert allowed_tag("B", ["b", "i"]) is True
    assert allowed_tag("bscript", ["b", "i"]) is False
    assert allowed_tag("scriptx", ["script"]) is False


def test_sanitize_attrs_strips_event_attributes():
    # Defect 2: on* handlers must not survive even when explicitly listed.
    attrs = {
        "href": "/safe",
        "onmouseover": "alert(1)",
        "OnError": "alert(2)",
    }
    allow = {"a": ["href", "onmouseover", "onerror"]}
    assert sanitize_attrs("A", attrs, allow) == {"href": "/safe"}


def test_sanitize_attrs_event_case_bypass():
    # Defect 3: removing only lowercase "onclick" leaves "OnClick" alive.
    attrs = {"OnClick": "alert(1)", "onclick": "alert(2)", "title": "ok"}
    allow = {"a": ["OnClick", "onclick", "title"]}
    assert sanitize_attrs("a", attrs, allow) == {"title": "ok"}


def test_safe_url_decodes_entities_before_scheme_check():
    # Defect 4: java&#115;cript: decodes to javascript:.
    assert safe_url("java&#115;cript:alert(1)", POLICY["url_schemes"]) is False
    assert safe_url("java&#x73;cript:alert(1)", POLICY["url_schemes"]) is False
    assert safe_url("java&amp;#115;cript:alert(1)", POLICY["url_schemes"]) is False
    assert safe_url("JaVaScRiPt:alert(1)", POLICY["url_schemes"]) is False
    assert safe_url("https://example.com/a?b=1", POLICY["url_schemes"]) is True


def test_safe_url_rejects_embedded_whitespace():
    # Defect 5: browsers ignore tabs/newlines inside a scheme.
    payloads = (
        "java\tscript:alert(1)",
        "java\nscript:alert(1)",
        "java\rscript:alert(1)",
        "java\x00script:alert(1)",
        "java\x0cscript:alert(1)",
        " java\tscript:alert(1) ",
    )
    for payload in payloads:
        assert safe_url(payload, POLICY["url_schemes"]) is False
    assert safe_url("httpsx:alert(1)", ["https"]) is False


def test_safe_url_restricts_data_mime():
    # Defect 6: allowing data: without a MIME allowlist permits HTML/SVG.
    assert (
        safe_url(
            "data:text/html;base64,PHNjcmlwdD5hbGVydCgxKTwvc2NyaXB0Pg==",
            ["data"],
        )
        is False
    )
    assert safe_url("data:image/svg+xml;base64,PHN2Zz48L3N2Zz4=", ["data"]) is False
    assert safe_url("data:image/png;base64,iVBORw0KGgo=", ["data"]) is True


def test_escape_text_escapes_single_quote():
    # Defect 7: an unescaped apostrophe escapes an attribute context.
    escaped = escape_text("<b>'\"&</b>")
    assert escaped == "&lt;b&gt;&#x27;&quot;&amp;&lt;/b&gt;"
    assert "'" not in escaped


def test_xss_script_inside_comment_is_removed():
    # Defect 8: a non-recursive comment path can preserve hidden script.
    payload = "<!--<script>alert(1)</script>-->"
    assert sanitize(payload, POLICY) == ""


def test_validate_policy_flags_style_and_other_danger():
    # Defect 9: CSS/style must be rejected by policy validation.
    bad = deepcopy(POLICY)
    bad["allowed_tags"].append("ScRiPt")
    bad["allowed_attrs"] = {"a": ["href", "OnClick"], "*": ["StYlE"]}
    bad["url_schemes"].append("DaTa")

    issues = validate_policy(bad)
    assert issues
    joined = " | ".join(issues).lower()
    for needle in ("script", "onclick", "style", "data"):
        assert needle in joined
    assert validate_policy(deepcopy(POLICY)) == []


def test_sanitize_batch_does_not_cache_dirty_policy():
    # Defect 10: a policy/cache mutated by part 1 must not affect part 2.
    policy = deepcopy(POLICY)
    snapshot = deepcopy(policy)
    parts = [
        "<b>one</b><script>alert(1)</script>",
        '<a href="javascript:alert(1)">two</a>',
    ]
    result = sanitize_batch(parts, policy)

    assert result["parts"] == ["<b>one</b>", "<a>two</a>"]
    assert result["changed"] is True
    assert policy == snapshot
    assert result["parts"][1] == sanitize(parts[1], policy)


def test_pure_text_is_lossless_and_unchanged():
    # Pure text must survive byte-for-byte; drift tolerance is 1e-9 (is 0).
    source = "纯文本评论 hello world 2026"
    assert tokenize(source) == [{"type": "text", "value": source, "raw": source}]
    result = sanitize(source, POLICY)
    assert _relative_text_drift(source, result) <= 1e-9
    assert result == source


def test_xss_script_is_removed_while_b_is_kept():
    source = "<b>安全</b><script>alert(1)</script><b>ok</b>"
    assert sanitize(source, POLICY) == "<b>安全</b><b>ok</b>"


def test_xss_dangerous_links_are_removed():
    source = (
        '<a href="javascript:alert(1)">js</a>'
        '<a href="data:text/html;base64,PHNjcmlwdD4=">data</a>'
        '<a href="https://example.com/x">ok</a>'
    )
    expected = (
        "<a>js</a>"
        "<a>data</a>"
        '<a href="https://example.com/x">ok</a>'
    )
    result = sanitize(source, POLICY)
    assert result == expected
    assert "javascript:" not in result.lower()
    assert "data:text/html" not in result.lower()


def test_xss_escaped_text_cannot_be_reparsed():
    escaped = escape_text("<img src=x onerror=alert(1)>")
    assert "<" not in escaped
    assert ">" not in escaped
    tokens = tokenize(escaped)
    assert tokens
    assert all(token["type"] == "text" for token in tokens)


def test_sanitize_batch_matches_individual_parts():
    # Fragments are independent and equal to one-at-a-time sanitization.
    parts = [
        "plain",
        "<b>ok</b>",
        '<a href="javascript:alert(1)">x</a>',
        "<!--<script>alert(1)</script>-->",
    ]
    batch = sanitize_batch(parts, POLICY)
    assert batch["parts"] == [sanitize(part, POLICY) for part in parts]
    assert batch["changed"] is True
